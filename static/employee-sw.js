const CACHE_NAME = "elfs-plan-employee-v3";
const OFFLINE_ASSETS = [
  "/employee",
  "/employee/dashboard",
  "/static/manifest.json",
  "/static/employee-icon-192.png",
  "/static/employee-icon-512.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(OFFLINE_ASSETS))
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) {
            return caches.delete(key);
          }
          return undefined;
        })
      )
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET" || !request.url.startsWith(self.location.origin)) {
    return;
  }

  const requestUrl = new URL(request.url);
  if (requestUrl.pathname.startsWith("/employee/api/")) {
    return;
  }
  if (!requestUrl.pathname.startsWith("/employee") && !requestUrl.pathname.startsWith("/static")) {
    return;
  }

  event.respondWith(
    fetch(request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        return response;
      })
      .catch(() => caches.match(request))
  );
});
